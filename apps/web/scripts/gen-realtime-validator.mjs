/* global console, process */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import prettier from 'prettier';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '../../..');
const schemaPath = path.resolve(rootDir, 'contracts/realtime/server.schema.json');
const outputPath = path.resolve(__dirname, '../src/lib/realtime/generated-server-validator.js');

export async function generateValidatorCode() {
  const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    strict: false,
    allErrors: true,
  });

  addFormats(ajv);

  const validate = ajv.compile(schema);
  let moduleCode = standaloneCode(ajv, validate);

  // Ajv standalone with esm: true still emits CommonJS require for runtime helpers (ucs2length, ajv-formats).
  // Convert them to native ES module imports so the generated module runs seamlessly in both
  // browser (strict CSP without unsafe-eval) and Node.js (Vitest) without CommonJS or eval.
  const importsHeader = `// AUTO-GENERATED by scripts/gen-realtime-validator.mjs - DO NOT EDIT MANUALLY
/* eslint-disable */
import ucs2length from 'ajv/dist/runtime/ucs2length.js';
import { fullFormats } from 'ajv-formats/dist/formats.js';
`;

  moduleCode = moduleCode.replace('"use strict";', `"use strict";\n${importsHeader}`);
  moduleCode = moduleCode.replaceAll(
    'require("ajv/dist/runtime/ucs2length").default',
    'ucs2length',
  );
  moduleCode = moduleCode.replaceAll(
    'require("ajv-formats/dist/formats").fullFormats',
    'fullFormats',
  );

  const config = (await prettier.resolveConfig(outputPath)) || {};
  const formatted = await prettier.format(moduleCode, {
    ...config,
    filepath: outputPath,
  });

  return formatted;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await generateValidatorCode();
  fs.writeFileSync(outputPath, code, 'utf8');
  console.log(`Generated realtime validator at: ${outputPath}`);
}
